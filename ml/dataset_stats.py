"""Auto-generate dataset statistics (B1) so the data docs never go stale. Needs only pandas.

Usage: python -m ml.dataset_stats            # writes data/DATA_CARD.md and docs/DATASET.md
"""
import ast
import hashlib
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def feature_list() -> list[str]:
    tree = ast.parse((ROOT / "ml" / "features.py").read_text(encoding="utf-8"))
    for n in tree.body:
        if isinstance(n, ast.Assign) and any(getattr(t, "id", "") == "FEATURES" for t in n.targets):
            return list(ast.literal_eval(n.value))
    raise RuntimeError("FEATURES not found in ml/features.py")


def md5(p: Path) -> str:
    return hashlib.md5(p.read_bytes()).hexdigest()[:12]


def build() -> str:
    tr = pd.read_csv(ROOT / "data" / "train.csv", parse_dates=["ts"])
    te = pd.read_csv(ROOT / "data" / "test.csv", parse_dates=["ts"])
    cut = tr.ts.quantile(0.8)                      # same rule as ml/train.py: last 20% of train (by time) = validation
    fit, va = tr[tr.ts < cut], tr[tr.ts >= cut]
    parts = {"train (fit)": fit, "validation (thresholds/model selection)": va, "test (final report)": te}
    L = ["<!-- AUTO-GENERATED by `python -m ml.dataset_stats`. Do not edit by hand. -->", "",
         "## Size, prevalence and time range", "", "| Part | Rows | Fraud (labelled) | Prevalence | From | To |", "|---|---|---|---|---|---|"]
    for n, d in parts.items():
        L.append(f"| {n} | {len(d):,} | {int(d.is_fraud.sum()):,} | {d.is_fraud.mean():.2%} | {d.ts.min():%Y-%m-%d %H:%M} | {d.ts.max():%Y-%m-%d %H:%M} |")
    al = pd.concat([tr, te])
    L += [f"| **all** | **{len(al):,}** | **{int(al.is_fraud.sum()):,}** | **{al.is_fraud.mean():.2%}** | {al.ts.min():%Y-%m-%d} | {al.ts.max():%Y-%m-%d} |", "",
          "## Scenarios (ground-truth typology column `scenario`, analysis only, never a model input)", "",
          "| Scenario | Train rows | Train labelled fraud | Test rows | Test labelled fraud |", "|---|---|---|---|---|"]
    a, b = tr.groupby("scenario").is_fraud.agg(["size", "sum"]), te.groupby("scenario").is_fraud.agg(["size", "sum"])
    for s in sorted(set(a.index) | set(b.index)):
        ra, rb = a.loc[s] if s in a.index else (0, 0), b.loc[s] if s in b.index else (0, 0)
        L.append(f"| {s} | {int(ra['size']) if s in a.index else 0:,} | {int(ra['sum']) if s in a.index else 0:,} | {int(rb['size']) if s in b.index else 0:,} | {int(rb['sum']) if s in b.index else 0:,} |")
    inj = al[al.scenario != "normal"]
    L += ["", f"Injected-fraud rows with `is_fraud=0` (the deliberate ~6% label noise): {int((inj.is_fraud == 0).sum()):,} of {len(inj):,} ({(inj.is_fraud == 0).mean():.1%}).", "",
          "## Leakage / overlap checks (computed)", "",
          f"- txn_id overlap train vs test: **{len(set(tr.txn_id) & set(te.txn_id))}**",
          f"- test users also present in train: **{te.user_id.isin(set(tr.user_id)).mean():.1%}** of test rows (users are shared by design: per-user history is a feature)",
          f"- recipient wallets in test already seen in train: **{te.recipient_id.isin(set(tr.recipient_id)).mean():.1%}** of test rows",
          f"- mule wallets (`MU*`) used in BOTH train and test: **{len({w for w in set(tr.user_id) | set(tr.recipient_id) if str(w).startswith('MU')} & {w for w in set(te.user_id) | set(te.recipient_id) if str(w).startswith('MU')})}**"
          " (the same 6 rings recur in the test period, so the test set does NOT measure detection of unseen rings)",
          f"- scenarios present in test but absent from train: **{sorted(set(te.scenario) - set(tr.scenario)) or 'none'}** (no held-out typology exists yet, see docs/AUDIT.md)", "",
          "## Model inputs", "", f"`ml/features.py` defines **{len(feature_list())}** model features:", "", ", ".join(f"`{f}`" for f in feature_list()), "",
          "## Files", "", f"- `data/train.csv` md5 `{md5(ROOT / 'data' / 'train.csv')}` · `data/test.csv` md5 `{md5(ROOT / 'data' / 'test.csv')}`"]
    return "\n".join(L) + "\n"


def main() -> None:
    stats = build()
    (ROOT / "data" / "DATA_CARD.md").write_text(
        "# Data card: UpayShield synthetic mobile-money dataset\n\n**Source: 100% SYNTHETIC** (generated by `scripts/generate_data.py`, seed 42, "
        "800 users, 40 agents, 30 days, Bangladesh-flavoured). No real customer data. Accuracy measured on it is optimistic.\n\n" + stats, encoding="utf-8")
    (ROOT / "docs" / "DATASET.md").write_text(
        "# Dataset\n\n> **Results measured on synthetic data.** The generator injects the fraud it later detects, so any accuracy number here is an "
        "upper bound on real-world performance.\n\nGeneration: `python scripts/generate_data.py --seed 42` (7 injected typologies, 6 mule rings of "
        "5 named wallets each (4 actually move money), ~6% of injected fraud left unlabelled as label noise, time-ordered 70/30 split into `data/train.csv` / `data/test.csv`; "
        "the validation slice is carved at train time by `ml/train.py`: last 20% of train by time). Column meanings: `data/README.md`.\n\n" + stats, encoding="utf-8")
    print("wrote data/DATA_CARD.md and docs/DATASET.md")


if __name__ == "__main__":
    main()
